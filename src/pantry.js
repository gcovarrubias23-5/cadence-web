export function foodsOf(kind) {
  return PANTRY.filter((p) => p.kind === kind)
}

export function portionFromPantry(item, grams) {
  const g = Number(grams) || item.base
  const n = g / 100
  return {
    name: item.name,
    aisle: item.aisle,
    kind: item.kind,
    grams: g,
    protein: item.protein * n,
    carbs: item.carbs * n,
    fat: item.fat * n,
    house: item.house,
    base: item.base,
    free: item.kind === 'free',
  }
}
